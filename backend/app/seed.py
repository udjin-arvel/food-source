def run_seed(session: Session) -> None:
    existing = session.exec(select(Supplier).limit(1)).first()
    if existing is not None:
        return

    for row in SEED_ROWS:
        data = dict(row)
        age = data.pop("age")
        sd = days_ago(age)
        created = datetime.combine(sd, datetime.min.time(), tzinfo=timezone.utc).replace(hour=9)
        supplier = Supplier(
            **data,
            source_date=sd,
            created_at=created,
        )
        session.add(supplier)
    session.commit()
